#!/bin/sh
set -e

# Xcode Cloud runs this from ios/ci_scripts/.
# CI_WORKSPACE is not always the git root; CI_PRIMARY_REPOSITORY_PATH is.
REPO_ROOT="${CI_PRIMARY_REPOSITORY_PATH:-${CI_WORKSPACE:-}}"
if [ -z "$REPO_ROOT" ] || [ ! -f "$REPO_ROOT/pubspec.yaml" ]; then
  REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
fi

# Install the full Flutter SDK (not Homebrew). Homebrew's flutter package
# is incomplete, so archive's Run Script (xcode_backend.sh) exits 65.
# https://docs.flutter.dev/deployment/cd#xcode-cloud
git clone https://github.com/flutter/flutter.git --depth 1 -b stable "$HOME/flutter"
export PATH="$HOME/flutter/bin:$PATH"
flutter precache --ios

cd "$REPO_ROOT"
flutter pub get

if [ -z "${MAPBOX_ACCESS_TOKEN:-}" ]; then
  echo "error: MAPBOX_ACCESS_TOKEN is not set." >&2
  echo "Add it in Xcode Cloud → Environment → Environment Variables (secret)." >&2
  echo "Local archives: flutter build ios --config-only --release --dart-define-from-file=dart_defines/dev.json" >&2
  exit 1
fi

# xcode_backend.sh rebuilds Generated.xcconfig without our CLI dart-defines.
# Persist DART_DEFINES in a gitignored xcconfig included *after* Generated.
ENCODED="$(python3 -c 'import base64, os; print(base64.b64encode(("MAPBOX_ACCESS_TOKEN=" + os.environ["MAPBOX_ACCESS_TOKEN"]).encode()).decode())')"
cat > "$REPO_ROOT/ios/Flutter/DartDefines.xcconfig" <<EOF
// Generated by ci_post_clone.sh — gitignored, do not commit.
DART_DEFINES=${ENCODED}
EOF

flutter build ios --config-only --release \
  --dart-define="MAPBOX_ACCESS_TOKEN=${MAPBOX_ACCESS_TOKEN}"

export HOMEBREW_NO_AUTO_UPDATE=1
brew install cocoapods

cd "$REPO_ROOT/ios"
pod install --repo-update
